def build_diagnosis_report(user_id: int, state: str, score: int, intake: dict, tests: list) -> dict:
    """
    Строит полный диагностический отчёт
    """
    severity = calculate_severity(score, state)
    therapies = get_therapy_types(state, severity["level"])
    
    report = {
        "state": state,
        "score": score,
        "severity": severity,
        "therapies": therapies,
        "intake": intake or {},
        "tests": tests or [],
        "timestamp": datetime.now().isoformat()
    }
    
    return report
